-- Territory map schema: markets, and the two span tables that carry the
-- 1926-1996 research. Nothing here is per-year; per-year is a view.
--
-- Grain matches wrestler_territory_runs (start_year/start_month/end_year/
-- end_month) so every span in this database reads the same way.

