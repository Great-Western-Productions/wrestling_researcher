-- The per-year shape, derived. Nothing stores a year; this explodes the spans
-- on demand so you can ask what 1968 looked like.
CREATE VIEW "public"."v_territory_year_markets" AS (
SELECT
  r.territory_id,
  t.name AS territory_name,
  g.year,
  r.market_id,
  m.name AS market_name,
  m.state,
  m.country,
  m.lat,
  m.lon,
  r.tier,
  r.confidence
FROM territory_market_runs r
JOIN territories t ON t.id = r.territory_id
JOIN markets m ON m.id = r.market_id
CROSS JOIN LATERAL generate_series(
  r.from_year,
  COALESCE(r.to_year, EXTRACT(YEAR FROM CURRENT_DATE)::integer)
) AS g(year));
